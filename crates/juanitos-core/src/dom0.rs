    #[test]
    fn the_shutdown_splash_runs_between_the_login_screen_and_the_qubes() {
        // rc.shutdown stops the `shutdown` scripts in reverse boot order.
        let s = RC_D_JOS_SPLASH_SHUTDOWN;
        assert!(s.contains("KEYWORD: shutdown"));
        assert!(s.contains("REQUIRE: LOGIN jos jos-splash-finish"));
        assert!(s.contains("BEFORE: jos-login"));
        assert!(s.find("--reached desktop --shutdown") < s.find("leave desktop"));
        for (script, leaves) in [
            (RC_D_JOS, "leave qubes"),
            (RC_D_JOS_SPLASH_NETWORK, "leave network"),
        ] {
            assert!(script.contains("KEYWORD: shutdown"), "{leaves}");
            assert!(script.contains(leaves));
            // The daemon names the step in progress itself.
            assert!(!script.contains("jos_splash_bin}\" status"), "{leaves}");
        }
        assert!(RC_D_JOS.contains("stage qubes"));
        assert!(RC_D_JOS_LOGIN.contains("KEYWORD: shutdown"));
        // Stopping the boot splash would end the shutdown one.
        assert!(!RC_D_JOS_SPLASH.contains("KEYWORD: shutdown"));
    }

    #[test]
    fn the_boot_splash_owns_the_screen_before_rc_prints() {
        // The kernel splash dies at the first console write; rc.d/kld and
        // rc.d/random echo even with rc_startmsgs=NO (seen under QEMU:
        // "Loading kernel modules:" over a black screen between the kernel
        // card and the daemon's first frame).
        let s = RC_D_JOS_SPLASH;
        assert!(s.contains("# REQUIRE: FILESYSTEMS jos-kms"));
        assert!(s.contains("# BEFORE: hostname kld random"));
        // daemon(8) returns at the fork: the script waits until the daemon
        // listens, which it only does after its first frame.
        let at = |needle: &str| s.find(needle).unwrap();
        assert!(at("--reached storage") < at("while [ ! -S \"${socket}\" ]"));
        assert!(at("rm -f \"${socket}\"") < at("--reached storage"));
        // The KMS driver replaces the framebuffer the daemon would map, and
        // kld_list would make rc.d/kld announce it.
        let k = RC_D_JOS_KMS;
        assert!(k.contains("# BEFORE: jos-splash kld"));
        assert!(k.contains("kldload -n \"${jos_kms_module}\""));
        assert!(!k.contains("echo"));
        // The fallback only when the real driver gave no KMS device.
        let at = |needle: &str| k.find(needle).unwrap();
        assert!(at("kldload -n \"${jos_kms_module}\"") < at("jos_kms_wait_card\n\tfi"));
        assert!(at("[ ! -c /dev/dri/card0 ]") < at("kldload -n \"${jos_kms_fallback}\""));
        // A local script cannot come before kld (first pass of /etc/rc).
        let files = static_files();
        for name in ["jos-kms", "jos-splash", "jos-bootok"] {
            let path = format!("/etc/rc.d/{name}");
            assert!(files.iter().any(|(p, _, _)| *p == path), "{name}");
        }
    }

