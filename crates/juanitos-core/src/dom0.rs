//! What turns a FreeBSD installation into a JuanitOS dom0.
//!
//! This is the single source of truth shared by the release builder
//! (`jos-release`, which assembles the live ISO and the dom0 tarball) and the
//! installer (`jos-install`, which lays the same tarball onto a ZFS pool).
//! Keeping both sides here is what guarantees the live medium and the
//! installed system are the *same* dom0, so passing `jos doctor` on the ISO
//! means the hardware will run the installed system.
//!
//! Everything is plain data (strings, lists); no host interaction happens
//! here.

/// Packages every dom0 needs. Names are FreeBSD `pkg` origins' package names.
pub const REQUIRED_PACKAGES: &[&str] = &[
    // bootrom for UEFI guests (sysutils/edk2@bhyve; the old
    // `uefi-edk2-bhyve` port is gone). Also installs the compatibility copy
    // at /usr/local/share/uefi-firmware/BHYVE_UEFI.fd that `jos` uses.
    "edk2-bhyve",
    "ca_root_nss", // TLS roots for `fetch`/`pkg`
    "seatd",       // seat management for the COSMIC compositor
    "dbus",
];

/// COSMIC desktop in dom0. These are installed best-effort: the FreeBSD
/// ports for COSMIC are young and a missing package must not break the
/// build (the installer and `jos` are fully usable from the console).
pub const GUI_PACKAGES: &[&str] = &[
    "cosmic-session",
    "cosmic-comp",
    "cosmic-greeter",
    "cosmic-panel",
    "cosmic-launcher",
    "cosmic-settings",
    "cosmic-term",
    "cosmic-files",
];

/// Packages needed to rebuild JuanitOS on JuanitOS (stage 2 of the
/// bootstrap, see `docs/bootstrap.md`).
pub const SELFHOST_PACKAGES: &[&str] = &["rust", "git"];

/// Kernel modules loaded at boot. `if_tap` is needed too but is compiled
/// into GENERIC (as part of `if_tuntap`) since FreeBSD 12, so listing it
/// here only produces "Unable to load kernel module" warnings; `jos doctor`
/// checks for it by module name instead.
pub const KERNEL_MODULES: &[&str] = &["vmm", "nmdm", "if_bridge"];

/// The `rc.d` script that autostarts qubes, installed as
/// `/usr/local/etc/rc.d/jos`.
pub const RC_D_JOS: &str = include_str!("../../../freebsd/rc.d/jos");

/// Boot splash hooks (see `docs/boot-splash.md`): start the daemon early,
/// light the network icon, end the splash before the greeter.
pub const RC_D_JOS_SPLASH: &str = include_str!("../../../freebsd/rc.d/jos-splash");
pub const RC_D_JOS_SPLASH_NETWORK: &str = include_str!("../../../freebsd/rc.d/jos-splash-network");
pub const RC_D_JOS_SPLASH_FINISH: &str = include_str!("../../../freebsd/rc.d/jos-splash-finish");

/// Kernel splash shown while the kernel boots muted (`loader.conf`
/// `splash=`), generated by `jos-release` from `jos-gfx`.
pub const BOOT_SPLASH_PNG: &str = "/boot/images/juanitos-splash.png";

/// The graphical pre-loader (`crates/jos-boot`), when the release ships it.
pub const JOS_BOOT_EFI: &str = "/boot/jos-boot.efi";

/// The `sys-firewall` unikernel boot image (`crates/jos-firewall`), when
/// the release ships it; `jos create --kernel` points here.
pub const FIREWALL_IMAGE: &str = "/usr/local/share/juanitos/jos-firewall.img";

/// FreeBSD's UEFI loader, always present in a dom0 root.
pub const LOADER_EFI: &str = "/boot/loader.efi";

/// Where the ESP keeps FreeBSD's loader; `jos-boot.efi` chain-loads this.
pub const ESP_LOADER: &str = "EFI/FREEBSD/LOADER.EFI";

/// The removable-media default path firmware boots without an entry.
pub const ESP_DEFAULT: &str = "EFI/BOOT/BOOTX64.EFI";

/// Files to place on an EFI system partition: `(source in the root,
/// destination relative to the ESP)`. With the pre-loader available it
/// becomes the default boot file and FreeBSD's loader moves to its own
/// directory; without it the loader is the default, as plain FreeBSD does.
pub fn esp_files(has_jos_boot: bool) -> Vec<(&'static str, &'static str)> {
    let mut files = vec![(LOADER_EFI, ESP_LOADER)];
    if has_jos_boot {
        files.push((JOS_BOOT_EFI, ESP_DEFAULT));
    } else {
        files.push((LOADER_EFI, ESP_DEFAULT));
    }
    files
}

