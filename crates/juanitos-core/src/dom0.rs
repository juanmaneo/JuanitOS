/// Files to place on an EFI system partition: `(source in the root,
/// destination relative to the ESP)`. With the pre-loader available it
/// becomes the default boot file and FreeBSD's loader moves to its own
/// directory; without it the loader is the default, as plain FreeBSD does.
pub fn esp_files(has_jos_boot: bool, has_ia32: bool) -> Vec<(&'static str, &'static str)> {
    let mut files = vec![(LOADER_EFI, ESP_LOADER)];
    if has_jos_boot {
        files.push((JOS_BOOT_EFI, ESP_DEFAULT));
    } else {
        files.push((LOADER_EFI, ESP_DEFAULT));
    }
    // jos-boot is x86_64-only: 32-bit firmware gets FreeBSD's loader.
    if has_ia32 {
        files.push((LOADER_IA32_EFI, ESP_IA32));
    }
    files
}

/// Where the default boot file goes on an EFI system partition shared with
/// other systems: a directory of JuanitOS's own, reached through a
/// firmware boot entry, so the removable-media default and the other
/// systems' directories stay as they are.
pub const ESP_SHARED: &str = "EFI/JUANITOS/BOOTX64.EFI";

/// [`esp_files`] for a shared ESP: the default boot file in
/// [`ESP_SHARED`], and no 32-bit loader (firmware that old has no other
/// system to share with).
pub fn esp_files_shared(has_jos_boot: bool) -> Vec<(&'static str, &'static str)> {
    esp_files(has_jos_boot, false)
        .into_iter()
        .map(|(src, dst)| (src, if dst == ESP_DEFAULT { ESP_SHARED } else { dst }))
        .collect()
}

