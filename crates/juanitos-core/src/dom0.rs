/// Which flavour of dom0 configuration to render.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Flavor {
    /// Read-only live medium running the installer.
    Live,
    /// Installed system booting from a ZFS pool.
    Installed,
}

/// Options that differ between hosts.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Dom0Options {
    pub hostname: String,
    /// Enable seatd/dbus at boot and the login screen on an installed
    /// system.
    pub gui: bool,
    /// Add a serial console next to the video console (handy under QEMU
    /// and for headless boxes).
    pub serial_console: bool,
    /// KMS driver to load for the dom0's own GPU (see
    /// [`gpu_kernel_module`]); `None` leaves the console on `vt(4)`'s
    /// framebuffer, which the compositor cannot use.
    pub gpu_module: Option<String>,
}

impl Default for Dom0Options {
    fn default() -> Self {
        Dom0Options {
            hostname: "juanitos".to_string(),
            gui: true,
            serial_console: true,
            gpu_module: None,
        }
    }
}

/// `/etc/rc.conf` for a dom0.
pub fn rc_conf(flavor: Flavor, opts: &Dom0Options) -> String {
    let mut s = String::new();
    s.push_str("# Generated by JuanitOS\n");
    s.push_str(&format!("hostname=\"{}\"\n", opts.hostname));
    s.push_str("sendmail_enable=\"NONE\"\n");
    s.push_str("sshd_enable=\"NO\"\n");
    let mut modules: Vec<&str> = KERNEL_MODULES.to_vec();
    if let Some(m) = opts.gpu_module.as_deref().filter(|_| opts.gui) {
        modules.push(m);
    }
    s.push_str(&format!("kld_list=\"{}\"\n", modules.join(" ")));
    match flavor {
        Flavor::Live => {
            s.push_str("# live medium: root is a read-only cd9660\n");
            s.push_str("root_rw_mount=\"NO\"\n");
            s.push_str("varmfs=\"YES\"\n");
            s.push_str("tmpmfs=\"YES\"\n");
            s.push_str("hostid_enable=\"NO\"\n");
            s.push_str("cron_enable=\"NO\"\n");
            s.push_str("jos_enable=\"NO\"\n");
        }
        Flavor::Installed => {
            s.push_str("zfs_enable=\"YES\"\n");
            s.push_str("dumpdev=\"AUTO\"\n");
            s.push_str("# JuanitOS qube autostart (see /usr/local/etc/rc.d/jos)\n");
            s.push_str("jos_enable=\"YES\"\n");
        }
    }
    if opts.gui {
        s.push_str("# COSMIC desktop in dom0 (no systemd needed)\n");
        s.push_str("seatd_enable=\"YES\"\n");
        s.push_str("dbus_enable=\"YES\"\n");
        if flavor == Flavor::Installed {
            s.push_str("# Login screen: jos-greet on ttyv8 (Alt+F9), see rc.d/jos-login\n");
            s.push_str("jos_login_enable=\"YES\"\n");
        }
    }
    s.push_str("# Graphical boot (see docs/boot-splash.md); Esc shows the console\n");
    s.push_str("jos_splash_enable=\"YES\"\n");
    s.push_str("rc_startmsgs=\"NO\"\n");
    s
}

/// `/boot/loader.conf` for a dom0. `pool` is the boot pool of an installed
/// system (unused for the live medium).
pub fn loader_conf(flavor: Flavor, opts: &Dom0Options) -> String {
    let mut s = String::new();
    s.push_str("# Generated by JuanitOS\n");
    for m in KERNEL_MODULES {
        s.push_str(&format!("{m}_load=\"YES\"\n"));
    }
    s.push_str("hw.vmm.iommu.enable=1\n");
    // Harmless on Intel (the tunable only exists for AMD-Vi), required on
    // AMD: without it vmm leaves the IOMMU off and passthrough fails.
    s.push_str("hw.vmm.amdvi.enable=1\n");
    match flavor {
        Flavor::Live => {
            s.push_str("vfs.mountroot.timeout=\"10\"\n");
            s.push_str("kernels_autodetect=\"NO\"\n");
            s.push_str("loader_menu_multi_user_prompt=\"Installer\"\n");
        }
        Flavor::Installed => {
            s.push_str("zfs_load=\"YES\"\n");
            s.push_str("cryptodev_load=\"YES\"\n");
            s.push_str("kern.geom.label.disk_ident.enable=\"0\"\n");
            s.push_str("kern.geom.label.gptid.enable=\"0\"\n");
        }
    }
    if opts.serial_console {
        // Kernel-side only: `console=` is deliberately not set here so the
        // pre-loader's `console=nullconsole` (quiet boot) is not overridden.
        s.push_str("# Serial console next to the video console (uart(4))\n");
        s.push_str("boot_multicons=\"YES\"\n");
        s.push_str("hw.uart.console=\"io:0x3f8,br:115200\"\n");
    }
    s.push_str("# Graphical boot: the kernel draws this while muted (jos-boot passes -m)\n");
    s.push_str(&format!("splash=\"{BOOT_SPLASH_PNG}\"\n"));
    s.push_str(&format!("shutdown_splash=\"{BOOT_SPLASH_PNG}\"\n"));
    s.push_str("kern.vt.splash_cpu=\"0\"\n");
    s.push_str("# Passthrough devices: see /usr/local/share/juanitos/loader.conf.sample\n");
    s.push_str("#pptdevs=\"1/0/0 1/0/1\"\n");
    s
}

/// `/etc/rc.local` on the live medium: hand the console to the installer.
pub fn live_rc_local() -> String {
    "#!/bin/sh
# JuanitOS live medium: run the installer on the console. Exit it to get a
# shell; `jos-install` can be re-run from there.
# rc.local runs before LOGIN, so end the boot splash here rather than in
# rc.d/jos-splash-finish: the installer needs the text console.
if [ -x /usr/local/bin/jos-splash ]; then
	/usr/local/bin/jos-splash stage desktop
	/usr/local/bin/jos-splash finish --console
fi
if [ -x /usr/local/bin/jos-install ]; then
	/usr/local/bin/jos-install --live < /dev/console > /dev/console 2>&1
fi
"
    .to_string()
}

/// `/etc/fstab` on the live medium (FreeBSD's `mkisoimages.sh` does the same).
pub fn live_fstab(label: &str) -> String {
    format!("/dev/iso9660/{label} / cd9660 ro 0 0\n")
}

/// Files installed into every dom0 besides the binaries. `(path, content,
/// executable)`; paths are absolute within the root. Contents are
/// normalised to LF: a `#!/bin/sh\r` from a Windows checkout would make
/// rc(8) skip the script.
pub fn static_files() -> Vec<(&'static str, String, bool)> {
    let lf = |s: &str| s.replace("\r\n", "\n");
    vec![
        ("/usr/local/etc/rc.d/jos", lf(RC_D_JOS), true),
        ("/usr/local/etc/rc.d/jos-splash", lf(RC_D_JOS_SPLASH), true),
        (
            "/usr/local/etc/rc.d/jos-splash-network",
            lf(RC_D_JOS_SPLASH_NETWORK),
            true,
        ),
        (
            "/usr/local/etc/rc.d/jos-splash-finish",
            lf(RC_D_JOS_SPLASH_FINISH),
            true,
        ),
        ("/usr/local/etc/rc.d/jos-login", lf(RC_D_JOS_LOGIN), true),
        ("/usr/local/libexec/jos-session", lf(JOS_SESSION), true),
        (PAM_JOS_GREET_PATH, lf(PAM_JOS_GREET), false),
        (
            "/usr/local/share/juanitos/loader.conf.sample",
            lf(LOADER_CONF_SAMPLE),
            false,
        ),
        (
            "/usr/local/share/juanitos/sysctl.conf.sample",
            lf(SYSCTL_CONF_SAMPLE),
            false,
        ),
    ]
}

