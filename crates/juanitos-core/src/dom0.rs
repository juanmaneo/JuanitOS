//! What turns a FreeBSD installation into a JuanitOS dom0.
//!
//! This is the single source of truth shared by the release builder
//! (`jos-release`, which assembles the live ISO and the dom0 tarball) and the
//! installer (`jos-install`, which lays the same tarball onto a ZFS pool).
//! Keeping both sides here is what guarantees the live medium and the
//! installed system are the *same* dom0, so passing `jos doctor` on the ISO
//! means the hardware will run the installed system.
//!
//! Everything is plain data (strings, lists); no host interaction happens
//! here.

/// Packages every dom0 needs. Names are FreeBSD `pkg` origins' package names.
