/// Overrides for the stock FreeBSD repositories (`/etc/pkg/FreeBSD.conf`).
pub const FREEBSD_REPO_CONF: &str = "/usr/local/etc/pkg/repos/FreeBSD.conf";

/// `juanitos.conf`: the local, unsigned COSMIC repository, preferred over
/// the FreeBSD ones for the packages it carries.
pub fn cosmic_repo_conf() -> String {
    format!(
        "# COSMIC packages built by JuanitOS (tools/dev/cosmic-build.sh)\n\
         juanitos: {{\n  url: \"file://{COSMIC_REPO_DIR}\",\n  \
         signature_type: \"none\",\n  enabled: yes,\n  priority: 10\n}}\n"
    )
}

/// `FreeBSD.conf`: point the stock repositories at `branch` (`quarterly`,
/// the default FreeBSD ships, or `latest`). The COSMIC packages are built
/// against one of them and their shared libraries must match, so the dom0
/// installs from the same branch as the build VM.
pub fn freebsd_repo_conf(branch: &str) -> String {
    format!(
        "# Generated by JuanitOS: the dom0 and its COSMIC packages track the \
         `{branch}` package branch\n\
         FreeBSD-ports: {{ url: \"pkg+https://pkg.FreeBSD.org/${{ABI}}/{branch}\" }}\n\
         FreeBSD-ports-kmods: {{ url: \"pkg+https://pkg.FreeBSD.org/${{ABI}}/kmods_{branch}_${{VERSION_MINOR}}\" }}\n"
    )
}

/// The kernel module `drm-kmod` provides for a GPU vendor, loaded at boot
/// so the compositor finds a KMS device. NVIDIA has no KMS driver in
/// `drm-kmod` (and in JuanitOS the NVIDIA card is passed through to the
/// `gpu` qube anyway).
pub fn gpu_kernel_module(vendor: u16) -> Option<&'static str> {
    match vendor {
        0x1002 => Some("amdgpu"),
        0x8086 => Some("i915kms"),
        _ => None,
    }
}

