//! Host side of the firewall: client addressing and rendering the config
//! disk a `sys-firewall` unikernel boots with.
//!
//! The rule grammar and the config-disk format live in the shared `no_std`
//! crate [`jos_fwcfg`] (re-exported here) so the unikernel parses exactly
//! what `jos` writes. In a qube's TOML:
//!
//! ```toml
//! firewall_policy = "deny"
//! firewall = ["allow tcp any 443", "allow udp 10.137.0.2 53", "allow icmp"]
//! ```

use std::collections::BTreeSet;
use std::net::Ipv4Addr;

pub use jos_fwcfg::{
    directives, evaluate, Action, Directive, Ipv4Net, MacAddr, PortRange, Proto, Rule,
    CONFIG_DISK_SLOT, MAX_CONFIG_BYTES, SECTOR,
};

use crate::config::{Qube, QubeKind};
use crate::error::{Error, Result};

/// Client addresses are carved out of this network, as in QubesOS.
pub const CLIENT_NET: Ipv4Net = Ipv4Net::new(Ipv4Addr::new(10, 137, 0, 0), 16);
/// First address handed out (`.0.0` is the network, `.0.1` is reserved).
const FIRST_CLIENT_HOST: u32 = 2;

/// Deterministic, locally administered unicast MAC for a qube's upstream
/// NIC: `02:4a` ("J") followed by a 32-bit FNV-1a hash of the name.
pub fn mac_for(name: &str) -> String {
    let mut h: u32 = 0x811c_9dc5;
    for b in name.bytes() {
        h ^= u32::from(b);
        h = h.wrapping_mul(0x0100_0193);
    }
    let b = h.to_be_bytes();
    MacAddr([0x02, 0x4a, b[0], b[1], b[2], b[3]]).to_string()
}

/// Pick the lowest free host address in [`CLIENT_NET`].
pub fn allocate_ip(used: &BTreeSet<Ipv4Addr>) -> Option<Ipv4Addr> {
    let base = u32::from(CLIENT_NET.addr);
    let last = base + (CLIENT_NET.size() as u32) - 2; // skip broadcast
    (base + FIRST_CLIENT_HOST..=last)
        .map(Ipv4Addr::from)
        .find(|ip| !used.contains(ip))
}

/// Addresses already assigned to `qubes`.
pub fn used_ips(qubes: &[Qube]) -> BTreeSet<Ipv4Addr> {
    qubes.iter().filter_map(|q| q.ip).collect()
}

/// Give `q` an address and MAC if it is a network client and has none.
/// Templates are clients too: they are only booted to be provisioned or
/// updated (`jos template install|run`), which needs the network.
pub fn assign_address(q: &mut Qube, others: &[Qube], default_netvm: Option<&str>) -> Result<()> {
    if q.kind == QubeKind::Net {
        return Ok(());
    }
    if q.resolve_netvm(default_netvm).is_none() {
        return Ok(());
    }
    if q.mac.is_none() {
        q.mac = Some(mac_for(&q.name));
    }
    if q.ip.is_none() {
        let used = used_ips(others);
        q.ip = Some(
            allocate_ip(&used)
                .ok_or_else(|| Error::Other(format!("no free address left in {CLIENT_NET}")))?,
        );
    }
    Ok(())
}

/// The qubes whose traffic goes through `netvm`.
pub fn clients_of<'a>(
    qubes: &'a [Qube],
    netvm: &str,
    default_netvm: Option<&str>,
) -> Vec<&'a Qube> {
    qubes
        .iter()
        .filter(|q| q.kind != QubeKind::Net)
        // Templates defined before they became clients have no address.
        .filter(|q| !q.is_template() || q.ip.is_some())
        .filter(|q| q.resolve_netvm(default_netvm) == Some(netvm))
        .collect()
}

/// Render the configuration a `sys-firewall` unikernel reads at boot (see
/// [`jos_fwcfg`] for the format). `fw` is the firewall qube itself; its
/// own `ip` is the clients' gateway.
pub fn render_config(fw: &Qube, clients: &[&Qube]) -> String {
    let mut out = String::new();
    out.push_str("# generated by jos; do not edit\n");
    out.push_str(&format!("firewall {}\n", fw.name));
    if let Some(ip) = fw.ip {
        out.push_str(&format!("gateway {ip}\n"));
    }
    out.push_str("upstream dhcp\n");
    for q in clients {
        let (Some(ip), Some(mac)) = (q.ip, &q.mac) else {
            continue;
        };
        out.push_str(&format!("client {} {ip} {mac}\n", q.name));
        for r in &q.firewall {
            out.push_str(&format!("rule {} {r}\n", q.name));
        }
        out.push_str(&format!("policy {} {}\n", q.name, q.firewall_policy));
    }
    out
}

/// Turn a rendered config into the bytes of a raw virtio-blk disk: the
/// text, NUL-terminated and zero-padded to a sector multiple.
pub fn config_disk_bytes(text: &str) -> Result<Vec<u8>> {
    if text.len() + 1 > MAX_CONFIG_BYTES {
        return Err(Error::Other(format!(
            "firewall config is {} bytes, more than the {MAX_CONFIG_BYTES} the unikernel reads",
            text.len()
        )));
    }
    let mut bytes = text.as_bytes().to_vec();
    bytes.push(0);
    let pad = (SECTOR - bytes.len() % SECTOR) % SECTOR;
    bytes.resize(bytes.len() + pad, 0);
    Ok(bytes)
}

/// A config disk parsed back into per-client tables (host-side twin of
/// what the unikernel builds), for `jos firewall` and tests.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct ParsedConfig {
    pub firewall: String,
    pub gateway: Option<Ipv4Addr>,
    pub clients: Vec<ParsedClient>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ParsedClient {
    pub name: String,
    pub ip: Ipv4Addr,
    pub mac: MacAddr,
    pub rules: Vec<Rule>,
    pub policy: Action,
}

pub fn parse_config(text: &str) -> Result<ParsedConfig> {
    let mut cfg = ParsedConfig::default();
    let unknown = |c: &str| Error::Other(format!("firewall config: rule for unknown client {c}"));
    for d in directives(text) {
        match d? {
            Directive::Firewall(n) => cfg.firewall = n.into(),
            Directive::Gateway(ip) => cfg.gateway = Some(ip),
            Directive::Upstream(_) => {}
            Directive::Client { name, ip, mac } => cfg.clients.push(ParsedClient {
                name: name.into(),
                ip,
                mac,
                rules: Vec::new(),
                policy: Action::Allow,
            }),
            Directive::Rule { client, rule } => cfg
                .clients
                .iter_mut()
                .rfind(|c| c.name == client)
                .ok_or_else(|| unknown(client))?
                .rules
                .push(rule),
            Directive::Policy { client, policy } => {
                cfg.clients
                    .iter_mut()
                    .rfind(|c| c.name == client)
                    .ok_or_else(|| unknown(client))?
                    .policy = policy
            }
        }
    }
    Ok(cfg)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::OsType;

    #[test]
    fn rules_serialize_as_strings_in_qube_toml() {
        let mut q = Qube::new("work", QubeKind::App, OsType::Freebsd);
        q.firewall = vec![
            "allow tcp any 443".parse().unwrap(),
            "deny".parse().unwrap(),
        ];
        q.firewall_policy = Action::Deny;
        q.ip = Some("10.137.0.5".parse().unwrap());
        q.mac = Some(mac_for("work"));
        let text = q.to_toml().unwrap();
        assert!(text.contains("firewall = [\n    \"allow tcp any 443\",\n    \"deny any any\",\n]"));
        assert!(text.contains("firewall_policy = \"deny\""));
        assert!(text.contains("ip = \"10.137.0.5\""));
        let back = Qube::from_toml(&text).unwrap();
        assert_eq!(back, q);
        assert!(Qube::from_toml(&text.replace("deny any any", "bogus")).is_err());
    }

    #[test]
    fn mac_is_deterministic_and_local() {
        let m = mac_for("work");
        assert_eq!(m, mac_for("work"));
        assert_ne!(m, mac_for("work2"));
        assert!(m.starts_with("02:4a:"));
        assert_eq!(m.len(), 17);
        assert!(m.parse::<MacAddr>().is_ok());
    }

    #[test]
    fn ip_allocation_skips_used() {
        let mut used = BTreeSet::new();
        assert_eq!(allocate_ip(&used), Some(Ipv4Addr::new(10, 137, 0, 2)));
        used.insert(Ipv4Addr::new(10, 137, 0, 2));
        used.insert(Ipv4Addr::new(10, 137, 0, 3));
        assert_eq!(allocate_ip(&used), Some(Ipv4Addr::new(10, 137, 0, 4)));
        assert!(CLIENT_NET.contains(Ipv4Addr::new(10, 137, 255, 254)));
    }

    #[test]
    fn offline_qubes_get_no_address_and_are_nobodys_client() {
        let mut vault = Qube::new("vault", QubeKind::App, OsType::Freebsd);
        vault.netvm = Some(crate::config::NO_NETVM.into());
        assign_address(&mut vault, &[], Some("sys-firewall")).unwrap();
        assert_eq!(vault.ip, None);
        assert_eq!(vault.mac, None);
        let mut work = Qube::new("work", QubeKind::App, OsType::Freebsd);
        assign_address(&mut work, &[], Some("sys-firewall")).unwrap();
        assert!(work.ip.is_some());
        let all = [vault, work];
        let clients = clients_of(&all, "sys-firewall", Some("sys-firewall"));
        assert_eq!(clients.len(), 1);
        assert_eq!(clients[0].name, "work");
    }

    #[test]
    fn assign_address_rules() {
        let fw = {
            let mut q = Qube::new("sys-firewall", QubeKind::Firewall, OsType::Unikernel);
            q.netvm = Some("sys-net".into());
            q.ip = Some(Ipv4Addr::new(10, 137, 0, 2));
            q
        };
        let mut work = Qube::new("work", QubeKind::App, OsType::Freebsd);
        assign_address(&mut work, std::slice::from_ref(&fw), Some("sys-firewall")).unwrap();
        assert_eq!(work.ip, Some(Ipv4Addr::new(10, 137, 0, 3)));
        assert_eq!(work.mac.as_deref(), Some(mac_for("work").as_str()));

        let mut net = Qube::new("sys-net", QubeKind::Net, OsType::Freebsd);
        assign_address(&mut net, &[], Some("sys-firewall")).unwrap();
        assert!(net.ip.is_none() && net.mac.is_none());

        let mut tmpl = Qube::new("t", QubeKind::Template, OsType::Freebsd);
        assign_address(&mut tmpl, &[], Some("sys-firewall")).unwrap();
        assert!(tmpl.ip.is_some(), "templates reach the network for updates");

        let mut isolated = Qube::new("iso", QubeKind::App, OsType::Freebsd);
        assign_address(&mut isolated, &[], None).unwrap();
        assert!(isolated.ip.is_none());

        // A MAC chosen earlier is kept.
        let mut kept = Qube::new("kept", QubeKind::App, OsType::Freebsd);
        kept.mac = Some("02:4a:00:00:00:01".into());
        assign_address(&mut kept, &[], Some("sys-firewall")).unwrap();
        assert_eq!(kept.mac.as_deref(), Some("02:4a:00:00:00:01"));
        // So is an address.
        let mut fixed = Qube::new("fixed", QubeKind::App, OsType::Freebsd);
        fixed.ip = Some(Ipv4Addr::new(10, 137, 0, 9));
        assign_address(&mut fixed, &[], Some("sys-firewall")).unwrap();
        assert_eq!(fixed.ip, Some(Ipv4Addr::new(10, 137, 0, 9)));

        // Every client address taken.
        let base = u32::from(CLIENT_NET.addr);
        let all: Vec<Qube> = (FIRST_CLIENT_HOST..CLIENT_NET.size() as u32 - 1)
            .map(|host| {
                let mut q = Qube::new("q", QubeKind::App, OsType::Freebsd);
                q.ip = Some(Ipv4Addr::from(base + host));
                q
            })
            .collect();
        let mut late = Qube::new("late", QubeKind::App, OsType::Freebsd);
        let err = assign_address(&mut late, &all, Some("sys-firewall")).unwrap_err();
        assert!(err.to_string().contains("no free address"), "{err}");
    }

    #[test]
    fn rendering_skips_what_has_no_address() {
        let fw = Qube::new("fw", QubeKind::Firewall, OsType::Unikernel);
        let mut bare = Qube::new("bare", QubeKind::App, OsType::Freebsd);
        bare.netvm = Some("fw".into());
        let text = render_config(&fw, &[&bare]);
        assert!(
            !text.contains("gateway") && !text.contains("bare"),
            "{text}"
        );
        let err = parse_config("policy ghost deny\n").unwrap_err();
        assert!(err.to_string().contains("unknown client ghost"), "{err}");
    }

    #[test]
    fn clients_and_rendered_config_roundtrip() {
        let mut fw = Qube::new("sys-firewall", QubeKind::Firewall, OsType::Unikernel);
        fw.netvm = Some("sys-net".into());
        fw.ip = Some(Ipv4Addr::new(10, 137, 0, 2));
        fw.mac = Some(mac_for("sys-firewall"));
        let mut work = Qube::new("work", QubeKind::App, OsType::Freebsd);
        work.ip = Some(Ipv4Addr::new(10, 137, 0, 3));
        work.mac = Some(mac_for("work"));
        work.firewall = vec!["allow tcp any 443".parse().unwrap()];
        work.firewall_policy = Action::Deny;
        let mut other = Qube::new("other", QubeKind::App, OsType::Linux);
        other.netvm = Some("sys-vpn".into());
        other.ip = Some(Ipv4Addr::new(10, 137, 0, 4));
        let net = Qube::new("sys-net", QubeKind::Net, OsType::Freebsd);
        let tmpl = Qube::new("fbsd14", QubeKind::Template, OsType::Freebsd);
        let mut dev = Qube::new("debian-13-dev", QubeKind::Template, OsType::Linux);
        dev.ip = Some(Ipv4Addr::new(10, 137, 0, 9));
        let all = vec![fw.clone(), work.clone(), other, net, tmpl, dev];

        let names: Vec<&str> = clients_of(&all, "sys-firewall", Some("sys-firewall"))
            .iter()
            .map(|q| q.name.as_str())
            .collect();
        assert_eq!(names, vec!["work", "debian-13-dev"]);
        let clients: Vec<&Qube> = all.iter().filter(|q| q.name == "work").collect();
        let upstream = clients_of(&all, "sys-net", Some("sys-firewall"));
        assert_eq!(upstream.len(), 1);
        assert_eq!(upstream[0].name, "sys-firewall");

        let text = render_config(&fw, &clients);
        assert!(text.contains("gateway 10.137.0.2\n"));
        assert!(text.contains(&format!("client work 10.137.0.3 {}\n", mac_for("work"))));
        assert!(text.contains("rule work allow tcp any 443\n"));
        assert!(text.contains("policy work deny\n"));

        let parsed = parse_config(&text).unwrap();
        assert_eq!(parsed.firewall, "sys-firewall");
        assert_eq!(parsed.gateway, Some(Ipv4Addr::new(10, 137, 0, 2)));
        assert_eq!(parsed.clients.len(), 1);
        assert_eq!(parsed.clients[0].rules, work.firewall);
        assert_eq!(parsed.clients[0].policy, Action::Deny);
        assert_eq!(parsed.clients[0].mac.to_string(), mac_for("work"));

        let disk = config_disk_bytes(&text).unwrap();
        assert_eq!(disk.len() % SECTOR, 0);
        assert!(disk.len() > text.len());
        let back = String::from_utf8_lossy(&disk);
        assert_eq!(parse_config(&back).unwrap(), parsed);
        assert!(parse_config("bogus line").is_err());
        assert!(parse_config("rule ghost allow").is_err());
        assert!(config_disk_bytes(&"x".repeat(MAX_CONFIG_BYTES)).is_err());
    }
}
