/// Look a glyph up; lowercase folds to uppercase.
pub fn glyph(c: char) -> &'static Glyph {
    let c = c.to_ascii_uppercase();
    GLYPHS
        .iter()
        .find(|(g, _)| *g == c)
        .map(|(_, rows)| rows)
        .unwrap_or(&UNKNOWN)
}

/// Width in pixels of `text` at integer `scale`.
pub fn text_width(text: &str, scale: i32) -> i32 {
    let n = text.chars().count() as i32;
    if n == 0 {
        0
    } else {
        (n * ADVANCE - 1) * scale
    }
}

pub fn text_height(scale: i32) -> i32 {
    GLYPH_HEIGHT * scale
}

/// Draw `text` with its top-left corner at (x, y).
pub fn draw_text(img: &mut Image, x: i32, y: i32, text: &str, scale: i32, c: Rgba) {
    let scale = scale.max(1);
    let mut pen = x;
    for ch in text.chars() {
        let rows = glyph(ch);
        for (ry, row) in rows.iter().enumerate() {
            for (rx, b) in row.bytes().enumerate() {
                if b == b'#' {
                    img.fill_rect(
                        Rect::new(pen + rx as i32 * scale, y + ry as i32 * scale, scale, scale),
                        c,
                    );
                }
            }
        }
        pen += ADVANCE * scale;
    }
}

/// Draw `text` horizontally centred on `cx`.
pub fn draw_text_centered(img: &mut Image, cx: i32, y: i32, text: &str, scale: i32, c: Rgba) {
    let x = cx - text_width(text, scale) / 2;
    draw_text(img, x, y, text, scale, c);
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_well_formed() {
        for (ch, rows) in GLYPHS {
            for row in rows {
                assert_eq!(row.len(), 5, "glyph {ch:?} row {row:?}");
                assert!(
                    row.bytes().all(|b| b == b'#' || b == b'.'),
                    "glyph {ch:?} row {row:?}"
                );
            }
        }
        // No duplicates.
        for (i, (a, _)) in GLYPHS.iter().enumerate() {
            assert!(
                GLYPHS.iter().skip(i + 1).all(|(b, _)| b != a),
                "duplicate glyph {a:?}"
            );
        }
    }

    #[test]
    fn lowercase_folds_and_unknown_is_boxed() {
        assert_eq!(glyph('a'), glyph('A'));
        assert_eq!(glyph('é'), &UNKNOWN);
    }

    #[test]
    fn widths() {
        assert_eq!(text_width("", 1), 0);
        assert_eq!(text_width("A", 1), 5);
        assert_eq!(text_width("AB", 1), 11);
        assert_eq!(text_width("AB", 2), 22);
        assert_eq!(text_height(3), 21);
    }

    #[test]
    fn draws_pixels() {
        let bg = Rgba::rgb(0, 0, 0);
        let fg = Rgba::rgb(255, 255, 255);
        let mut img = Image::new(16, 16, bg);
        draw_text(&mut img, 1, 1, "I", 1, fg);
        // Top bar of 'I' spans columns 1..=3 of the glyph.
        assert_eq!(img.get(2, 1), Some(fg));
        assert_eq!(img.get(3, 1), Some(fg));
        assert_eq!(img.get(1, 1), Some(bg));
        assert_eq!(img.get(3, 2), Some(fg));
        // Scaled drawing fills blocks.
        let mut big = Image::new(32, 32, bg);
        draw_text(&mut big, 0, 0, "|", 3, fg);
        assert_eq!(big.get(6, 0), Some(fg));
        assert_eq!(big.get(8, 2), Some(fg));
        assert_eq!(big.get(9, 0), Some(bg));
    }
}
